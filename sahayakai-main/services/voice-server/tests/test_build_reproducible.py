"""CLASS GATE — the deploy builds the image it tested, from pinned packages.

Independent review #14: the image was rebuilt with `pip install -e .` against
open ranges (pipecat-ai>=0.0.108, google-genai>=0.8, ...), so every candidate
resolved whatever was newest that day, not what production ran. And the
build's only test step stubbed pipecat, so a dependency API change (which had
already broken this service twice) could not fail the build.

The class is "the deployed image is not the one the gates saw". The gate:
the Dockerfile installs only from a hashed lock and nothing else; the lock, when
present, pins every package with a hash and covers every direct dependency;
requirements.in and pyproject agree; and the Cloud Build pipeline runs the
real-pipecat smoke check inside the built image before it pushes or deploys.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
DOCKERFILE = (ROOT / "Dockerfile").read_text(encoding="utf-8")
CLOUDBUILD = (ROOT / "cloudbuild.yaml").read_text(encoding="utf-8")
LOCK = ROOT / "requirements.lock"


def _names(lines):
    out = set()
    for line in lines:
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        out.add(re.split(r"[\[<>=!~ ;]", line, maxsplit=1)[0].lower().replace("_", "-"))
    return out


def _pyproject_dependencies() -> set[str]:
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    block = re.search(r"dependencies\s*=\s*\[(.*?)\n\]", text, re.S).group(1)
    return _names(re.findall(r'"([^"]+)"', block))


def test_the_dockerfile_installs_only_from_the_hashed_lock():
    installs = [line.strip() for line in DOCKERFILE.splitlines() if "pip install" in line]
    assert installs, "no pip install found"
    joined = " ".join(installs)
    assert "--require-hashes -r requirements.lock" in joined
    for line in installs:
        assert "requirements.lock" in line or "--no-deps" in line, f"resolves dependencies outside the lock: {line}"
    assert re.search(r"^COPY .*requirements\.lock", DOCKERFILE, re.M), "the lock is not copied into the build"


def test_requirements_in_and_pyproject_name_the_same_packages():
    assert _names((ROOT / "requirements.in").read_text(encoding="utf-8").splitlines()) == _pyproject_dependencies()


def lock_problems(text: str, required: set[str]) -> list[str]:
    """What is wrong with a pip-compile --generate-hashes lock."""
    problems, pinned = [], set()
    for entry in re.split(r"\n(?=[A-Za-z0-9])", text):
        head = entry.strip().splitlines()[0] if entry.strip() else ""
        if not head or head.startswith("#"):
            continue
        m = re.match(r"([A-Za-z0-9_.\-]+)(?:\[[^\]]*\])?==([^\s\\]+)", head)
        if not m:
            problems.append(f"not pinned with ==: {head}")
            continue
        if "--hash=sha256:" not in entry:
            problems.append(f"no hash for {m.group(1)}")
        pinned.add(m.group(1).lower().replace("_", "-"))
    problems += [f"direct dependency not in the lock: {n}" for n in sorted(required - pinned)]
    return problems


GOOD_LOCK = """# generated by pip-compile
fastapi==0.115.0 \\
    --hash=sha256:aaaa
pipecat-ai[google]==1.2.1 \\
    --hash=sha256:bbbb \\
    --hash=sha256:cccc
"""


def test_the_lock_checker_accepts_a_hashed_lock_and_rejects_loose_ones():
    assert lock_problems(GOOD_LOCK, {"fastapi", "pipecat-ai"}) == []
    assert lock_problems("fastapi>=0.115 \\\n    --hash=sha256:aaaa\n", {"fastapi"})
    assert lock_problems("fastapi==0.115.0\n", {"fastapi"})
    assert lock_problems(GOOD_LOCK, {"fastapi", "pipecat-ai", "httpx"}) == ["direct dependency not in the lock: httpx"]


def test_the_lock_if_present_pins_every_package_with_a_hash():
    if not LOCK.exists():
        pytest.skip("requirements.lock not generated yet (scripts/lock.sh needs PyPI); the image build fails closed until it is")
    assert lock_problems(LOCK.read_text(encoding="utf-8"), _pyproject_dependencies()) == []


def _steps():
    # Text-level: step ids in order, with each step's waitFor and body.
    steps = []
    for block in re.split(r"\n  - id: ", CLOUDBUILD)[1:]:
        sid = block.split("\n", 1)[0].strip()
        wait = re.search(r"waitFor:\s*\[([^\]]*)\]", block)
        steps.append((sid, block, [w.strip() for w in wait.group(1).split(",")] if wait else []))
    return steps


def test_the_build_runs_the_real_pipecat_smoke_check_in_the_built_image_before_push_and_deploy():
    steps = {sid: (body, wait) for sid, body, wait in _steps()}
    assert "smoke-real-pipecat" in steps, "no real-pipecat step"
    body, wait = steps["smoke-real-pipecat"]
    image = re.search(r"--tag=(\S+)", steps["build"][0]).group(1)
    assert "- run" in body and image in body and "src.smoke_check" in body, "the smoke step must run inside the built image"
    assert wait == ["build"]
    assert steps["push"][1] == ["smoke-real-pipecat"], "push must wait for the smoke check"
    assert steps["deploy-candidate"][1] == ["push"]


def test_the_smoke_check_imports_the_server_and_builds_both_backends():
    source = (ROOT / "src" / "smoke_check.py").read_text(encoding="utf-8")
    tree = ast.parse(source)
    imports = {n.names[0].name for n in ast.walk(tree) if isinstance(n, ast.Import)} | \
              {n.module for n in ast.walk(tree) if isinstance(n, ast.ImportFrom) and n.module}
    assert {"src.main", "src.bot"} <= imports
    assert "ai_studio" in source and "vertex" in source and "create_bot" in source
    # Every pipecat module the engine imports is either imported by src.main
    # (and so by the smoke check) or named in REQUIRED_PIPECAT.
    engine_pipecat = set()
    for path in (ROOT / "src").glob("*.py"):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("pipecat"):
                engine_pipecat.add(node.module)
    assert engine_pipecat, "the scan found no pipecat imports"

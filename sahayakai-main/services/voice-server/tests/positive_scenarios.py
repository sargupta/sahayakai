async def capture(name: str) -> dict:
    """Everything observable about one positive scenario (call inside stubbed_runtime)."""
    scenario = SCENARIOS[name]
    store = None if scenario.get("no_store") else FakeCallStore(history=scenario["history"])
    run = await build_bot(scenario["context"], call_store=store)
    greeting = await spoken_greeting(run)
    guidance = await phase_guidance(run)
    replacement, added = await ai_reveal_replacement(run)
    return {
        "greeting": greeting,
        "system_instruction": run.system_instruction,
        "seed_messages": run.seed_messages,
        "phase_guidance": guidance,
        "llm_settings": run.llm_settings,
        "stt_settings": run.stt_settings,
        "tts_settings": run.tts_settings,
        "ai_reveal_replacement": replacement,
        "ai_reveal_context": added,
        "history_requested_for": store.history_requests if store else None,
    }


def capture_all() -> dict:
    import asyncio

    out = {}
    for name in SCENARIOS:
        with stubbed_runtime():
            out[name] = asyncio.run(capture(name))
    return out

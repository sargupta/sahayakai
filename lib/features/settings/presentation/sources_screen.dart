import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../../core/platform/link_opener.dart';
import '../../../core/theme/app_theme.dart';
import '../../../shared/widgets/glass_app_bar.dart';

/// One official source the app's syllabus content is based on.
class OfficialSource {
  const OfficialSource(this.name, this.url);

  final String name;
  final String url;
}

/// The government sources behind the syllabus references in the app.
///
/// Google Play's Misleading Claims policy requires an app that presents
/// government information (NCERT / CBSE / state-board syllabi) to link to the
/// original source and to say it is not a government app. Keep this list and
/// the store-listing description in step.
const officialSources = <OfficialSource>[
  OfficialSource(
    'NCERT textbooks (National Council of Educational Research and Training)',
    'https://ncert.nic.in/textbook.php',
  ),
  OfficialSource('NCERT syllabus', 'https://ncert.nic.in/syllabus.php'),
  OfficialSource(
    'CBSE curriculum (Central Board of Secondary Education)',
    'https://cbseacademic.nic.in/',
  ),
  OfficialSource(
    'Ministry of Education, Government of India',
    'https://www.education.gov.in/',
  ),
  OfficialSource(
    'DIKSHA (national digital teaching platform)',
    'https://diksha.gov.in/',
  ),
];

/// Settings → Sources & disclaimer: not a government app, plus links to the
/// official syllabus sources.
class SourcesScreen extends ConsumerWidget {
  const SourcesScreen({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final scheme = Theme.of(context).colorScheme;
    final text = Theme.of(context).textTheme;
    final body = text.bodyMedium?.copyWith(color: scheme.onSurfaceVariant);
    final heading = text.titleMedium?.copyWith(color: scheme.onSurface);

    return Scaffold(
      appBar: const GlassAppBar(title: Text('Sources & disclaimer')),
      body: SafeArea(
        child: ListView(
          padding: AppSpacing.pagePadding,
          children: [
            Text('Not a government app', style: heading),
            const SizedBox(height: AppSpacing.space2),
            Text(
              'SahayakAI is made by SARGVISION, a private company. It is not a '
              'government app. It is not affiliated with, endorsed by, or acting '
              'on behalf of NCERT, CBSE, the Ministry of Education, or any state '
              'government or state education board.',
              style: body,
            ),
            const SizedBox(height: AppSpacing.space4),
            Text('Where syllabus information comes from', style: heading),
            const SizedBox(height: AppSpacing.space2),
            Text(
              'Lesson plans, quizzes, worksheets and exam papers follow the '
              'syllabus and textbooks published by these official sources. '
              'Check them for the latest syllabus, textbooks and exam rules:',
              style: body,
            ),
            const SizedBox(height: AppSpacing.space2),
            for (final source in officialSources)
              _SourceLink(
                source: source,
                onOpen: () => _open(context, ref, source),
              ),
            const SizedBox(height: AppSpacing.space2),
            Text(
              'For state board syllabi, see your state education board\'s '
              'official website.',
              style: body,
            ),
            const SizedBox(height: AppSpacing.space4),
            Text('AI-generated content', style: heading),
            const SizedBox(height: AppSpacing.space2),
            Text(
              'Content made by SahayakAI is generated by AI and can contain '
              'mistakes. Check it against the official textbook before using '
              'it in class.',
              style: body,
            ),
          ],
        ),
      ),
    );
  }

  Future<void> _open(
    BuildContext context,
    WidgetRef ref,
    OfficialSource source,
  ) async {
    var opened = false;
    try {
      opened = await ref.read(linkOpenerProvider).open(Uri.parse(source.url));
    } on PlatformException {
      opened = false;
    }
    if (opened || !context.mounted) return;
    // No browser to hand off to: copy the link so the teacher can still reach it.
    await Clipboard.setData(ClipboardData(text: source.url));
    if (!context.mounted) return;
    ScaffoldMessenger.of(context)
      ..hideCurrentSnackBar()
      ..showSnackBar(
        SnackBar(
          content: Text('Couldn\'t open a browser. Link copied: ${source.url}'),
        ),
      );
  }
}

class _SourceLink extends StatelessWidget {
  const _SourceLink({required this.source, required this.onOpen});

  final OfficialSource source;
  final VoidCallback onOpen;

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final text = Theme.of(context).textTheme;
    return Semantics(
      link: true,
      label: '${source.name}, ${source.url}',
      excludeSemantics: true,
      child: InkWell(
        onTap: onOpen,
        child: ConstrainedBox(
          constraints: const BoxConstraints(minHeight: 48),
          child: Padding(
            padding: const EdgeInsets.symmetric(vertical: 8),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  source.name,
                  style: text.bodyMedium?.copyWith(color: scheme.onSurface),
                ),
                Text(
                  source.url,
                  style: text.bodyMedium?.copyWith(
                    color: scheme.primary,
                    decoration: TextDecoration.underline,
                  ),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }
}
